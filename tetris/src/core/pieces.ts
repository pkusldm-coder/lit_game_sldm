export const PIECE_TYPES: PieceType[] = ['I', 'O', 'T', 'S', 'Z', 'J', 'L']

const BAG: PieceType[] = ['I', 'O', 'T', 'S', 'Z', 'J', 'L']

function shuffle<T>(a: T[]): T[] {
  const arr = [...a]
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]]
  }
  return arr
}

let _bag: PieceType[] = []

export function nextPiece(): PieceType {
  if (_bag.length === 0) _bag = shuffle(BAG)
  return _bag.pop()!
}

export function peekNext(): PieceType | null {
  if (_bag.length === 0) _bag = shuffle(BAG)
  return _bag[_bag.length - 1] ?? null
}

export function resetBag(): void {
  _bag = []
}
